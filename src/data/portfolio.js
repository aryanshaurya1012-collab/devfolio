export function getActiveTheme(themeKey = "obsidian", mode = "dark") {
  const base = THEMES[themeKey] || THEMES.obsidian;
  const currentMode = mode === "light" ? "light" : "dark";
  const config = base[currentMode] || base.dark;
  return {
    id: base.id,
    name: base.name,
    pillColor: base.pillColor,
    accent: base.accent,
    mode: currentMode,
    ...config,
  };
}

